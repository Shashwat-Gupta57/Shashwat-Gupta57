"""Writes js/releases.js — the latest GitHub release of each project, with every asset's size,
download URL and SHA-256 (GitHub's own digest when it has one, else hashed locally from the
release zip in Published/_build/dist). Feeds each project's Download page.

Run from the repo root:  python -I tools/releases.py"""
import hashlib, json, os, subprocess

OWNER = 'Shashwat-Gupta57'
DIST = r'D:\User\Data\projects\Published\_build\dist'
REPOS = {
    'rex-run': 'Rex-Run', 'flying-dual': 'Flying-Dual', 'ping-pong': 'Ping-Pong', 'notes': 'Notes',
    'widgets': 'Widgets', 'sg-paint': 'SG-Paint', 'jre-installer': 'JRE-Installer', 'flappy-bird': 'Flappy-Bird',
    'memo': 'Memo', 'color-picker': 'Color-Picker', 'tic-tac-toe': 'Tic-Tac-Toe', 'terminal-game': 'Terminal-Game',
    'codemeter': 'CodeMeter', 'jctx': 'Jctx', 'nglobe': 'NGlobe', 'backbench': 'Backbench', 'workdesk': 'WorkDesk',
}


def gh(*args):
    r = subprocess.run(['gh', *args], capture_output=True, text=True, encoding='utf-8')
    return r.stdout if r.returncode == 0 else None


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


out = {}
for pid, repo in REPOS.items():
    raw = gh('api', f'repos/{OWNER}/{repo}/releases/latest')
    if not raw:
        print(f'{pid:16s} no release')
        continue
    rel = json.loads(raw)
    assets = []
    for a in rel.get('assets', []):
        digest = (a.get('digest') or '').replace('sha256:', '')
        local = os.path.join(DIST, a['name'])
        if not digest and os.path.exists(local) and os.path.getsize(local) == a['size']:
            digest = sha256(local)
        assets.append({'name': a['name'], 'size': a['size'], 'url': a['browser_download_url'], 'sha256': digest, 'downloads': a.get('download_count', 0)})
    out[pid] = {'repo': repo, 'tag': rel['tag_name'], 'name': rel.get('name') or rel['tag_name'],
                'date': rel['published_at'][:10], 'url': rel['html_url'], 'assets': assets}
    print(f'{pid:16s} {rel["tag_name"]:10s} {len(assets)} assets')

path = os.path.join(os.path.dirname(__file__), '..', 'js', 'releases.js')
with open(path, 'w', encoding='utf-8') as fh:
    fh.write('/* Generated by tools/releases.py from GitHub Releases — do not edit by hand. */\n')
    fh.write('window.RELEASES = ' + json.dumps(out, indent=1) + ';\n')
